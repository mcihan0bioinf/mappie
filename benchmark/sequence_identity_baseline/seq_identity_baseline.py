#!/usr/bin/env python3
"""Baseline: rank PPIs by raw sequence identity instead of latent cosine
similarity. seq_sim((A,B),(C,D)) = max(id(A,C)+id(B,D), id(A,D)+id(B,C)).
Same exclusion/metrics as the STRING benchmark for direct comparison.

results/seq_identity_v2_clean_params.tsv is pre-generated by:
    mmseqs easy-search data/proteins.fasta data/proteins.fasta \\
        results/seq_identity_v2_clean_params.tsv tmp_mmseqs \\
        --format-output "query,target,pident" \\
        -s 7.5 -c 0.5 --cov-mode 0 -e 0.001 --threads 8
"""

from pathlib import Path
from collections import defaultdict

import numpy as np
import pandas as pd
from scipy.sparse import coo_matrix
import warnings
import os
warnings.filterwarnings("ignore")

ROOT        = Path(__file__).resolve().parent
MAPPIE_ROOT = Path(os.environ.get("MAPPIE_ROOT", "../mappie"))
LATENT_FILE = MAPPIE_ROOT / "data_processed/latent_index.npz"
IDENTITY_TSV = ROOT / "results/seq_identity_v2_clean_params.tsv"
STRING_PAIRS = ROOT.parent / "string_comparison/results/string_mappie_pairs.csv"
OUT_DIR      = ROOT / "results"
OUT_DIR.mkdir(exist_ok=True)

K_SWEEP = [10, 25, 50, 100, 200, 500]
K_MAX   = 1000  # match MAPPIE benchmark search horizon (1,000 neighbours)

print("Loading MAPPIE PPI universe ...")
_z       = np.load(LATENT_FILE, allow_pickle=True)
all_keys = list(np.asarray(_z["keys"], dtype=str))
n_all    = len(all_keys)
print(f"  {n_all:,} PPIs")

pos_to_prots = []
for k in all_keys:
    parts = k.split("_HUMAN_")
    pos_to_prots.append((parts[0] + "_HUMAN", parts[1]) if len(parts) == 2 else (None, None))

key_to_i = {k: i for i, k in enumerate(all_keys)}
latent_set = set(all_keys)

print("Loading sequence identity matrix ...")
id_df = pd.read_csv(IDENTITY_TSV, sep="\t", header=None, names=["query", "target", "pident"])
proteins = sorted(set(id_df["query"]) | set(id_df["target"]))
prot_to_idx = {p: i for i, p in enumerate(proteins)}
n_prot = len(proteins)
print(f"  {n_prot:,} proteins, {len(id_df):,} pairwise hits")

rows = id_df["query"].map(prot_to_idx).to_numpy()
cols = id_df["target"].map(prot_to_idx).to_numpy()
vals = id_df["pident"].to_numpy(dtype=np.float32)
identity_mat = coo_matrix((vals, (rows, cols)), shape=(n_prot, n_prot)).tocsr()

row_cache: dict[int, np.ndarray] = {}
def get_row(idx: int) -> np.ndarray:
    if idx not in row_cache:
        row_cache[idx] = identity_mat.getrow(idx).toarray().ravel()
    return row_cache[idx]

# Protein index arrays for every MAPPIE PPI position (-1 if protein unknown)
protA_idx = np.array([prot_to_idx.get(a, -1) if a else -1 for a, b in pos_to_prots], dtype=np.int64)
protB_idx = np.array([prot_to_idx.get(b, -1) if b else -1 for a, b in pos_to_prots], dtype=np.int64)
# Map -1 to a dummy zero-row index by clipping; we'll zero those scores explicitly
valid_mask = (protA_idx >= 0) & (protB_idx >= 0)
protA_safe = np.clip(protA_idx, 0, n_prot - 1)
protB_safe = np.clip(protB_idx, 0, n_prot - 1)

def rank_candidates(idxA: int, idxB: int, exclude_prots: set[str], self_pos: int) -> np.ndarray:
    """Return positions ordered by descending sequence-identity score (top K_MAX)."""
    rowA = get_row(idxA)
    rowB = get_row(idxB)
    idA_A = rowA[protA_safe]; idA_B = rowA[protB_safe]
    idB_A = rowB[protA_safe]; idB_B = rowB[protB_safe]
    score = np.maximum(idA_A + idB_B, idA_B + idB_A)
    score[~valid_mask] = -1.0

    # shared-protein exclusion: mark any PPI containing one of the query proteins
    excl_mask = np.zeros(n_all, dtype=bool)
    for ex in exclude_prots:
        exi = prot_to_idx.get(ex, -999)
        excl_mask |= (protA_idx == exi) | (protB_idx == exi)
    if self_pos is not None and 0 <= self_pos < n_all:
        excl_mask[self_pos] = True
    score[excl_mask] = -np.inf

    top_n = min(K_MAX + 5, n_all)
    top_idx = np.argpartition(-score, top_n - 1)[:top_n]
    top_idx = top_idx[np.argsort(-score[top_idx])]
    return top_idx

def eval_query(idxA, idxB, mA, mB, network: set[str]) -> dict:
    self_pos = key_to_i.get(f"{mA}_{mB}", key_to_i.get(f"{mB}_{mA}"))
    ranked = rank_candidates(idxA, idxB, {mA, mB}, self_pos)

    result = {"mrr": 0.0, "coverage": {}, "precision": {}}
    found_rank = None
    for rank, pos in enumerate(ranked, 1):
        a, b = pos_to_prots[pos]
        if a in network or b in network:
            found_rank = rank
            break
    if found_rank:
        result["mrr"] = 1.0 / found_rank

    for k in K_SWEEP:
        nbrs_k = ranked[:k]
        knn_prots = set()
        for pos in nbrs_k:
            a, b = pos_to_prots[pos]
            if a: knn_prots.add(a)
            if b: knn_prots.add(b)
        cov = len(network & knn_prots) / len(network) if network else float("nan")
        n_pos = sum(1 for pos in nbrs_k if pos_to_prots[pos][0] in network or pos_to_prots[pos][1] in network)
        prec = n_pos / len(nbrs_k) if len(nbrs_k) > 0 else float("nan")
        result["coverage"][k] = cov
        result["precision"][k] = prec
    return result


def run_benchmark(name: str, queries: list[tuple[str, str]], get_network, out_prefix: str):
    cov_sum  = {k: 0.0 for k in K_SWEEP}; cov_cnt = {k: 0 for k in K_SWEEP}
    prec_sum = {k: 0.0 for k in K_SWEEP}; prec_cnt = {k: 0 for k in K_SWEEP}
    mrr_sum  = 0.0; mrr_cnt = 0

    n = len(queries)
    for i, (mA, mB) in enumerate(queries):
        idxA = prot_to_idx.get(mA); idxB = prot_to_idx.get(mB)
        if idxA is None or idxB is None:
            continue
        network = get_network(mA, mB)
        if not network:
            continue
        res = eval_query(idxA, idxB, mA, mB, network)
        mrr_sum += res["mrr"]; mrr_cnt += 1
        for k in K_SWEEP:
            c, p = res["coverage"][k], res["precision"][k]
            if not np.isnan(c):
                cov_sum[k] += c; cov_cnt[k] += 1
            if not np.isnan(p):
                prec_sum[k] += p; prec_cnt[k] += 1
        if i % 5000 == 0:
            print(f"  [{name}] {i:,}/{n:,}")

    print(f"\n=== {name}: sequence-identity baseline ===")
    print(f"  (fold enrichment computed in 02_comparison_plot.py using exact hypergeometric random from MAPPIE CSVs)")
    print(f"{'k':>6}  {'coverage':>10}  {'precision':>10}")
    rows_out = []
    for k in K_SWEEP:
        c = cov_sum[k] / cov_cnt[k] if cov_cnt[k] > 0 else float("nan")
        p = prec_sum[k] / prec_cnt[k] if prec_cnt[k] > 0 else float("nan")
        print(f"{k:>6}  {c:>10.4f}  {p:>10.4f}")
        rows_out.append({"k": k, "coverage": round(c, 4), "precision": round(p, 4)})
    mrr = mrr_sum / mrr_cnt if mrr_cnt > 0 else float("nan")
    print(f"  MRR = {mrr:.4f}  (n={mrr_cnt:,})")

    pd.DataFrame(rows_out).to_csv(OUT_DIR / f"{out_prefix}_coverage.csv", index=False)
    pd.DataFrame([{"mrr": round(mrr, 4), "n": mrr_cnt}]).to_csv(OUT_DIR / f"{out_prefix}_mrr.csv", index=False)
    return rows_out, mrr


print("\n--- STRING sequence-identity baseline ---")
str_df = pd.read_csv(STRING_PAIRS)
prot_string: dict[str, dict[str, int]] = defaultdict(dict)
for _, row in str_df.iterrows():
    p1, p2, sc = row["prot1"], row["prot2"], int(row["combined_score"])
    prot_string[p1][p2] = sc
    prot_string[p2][p1] = sc

string_queries = []
for k in str_df["ppikey"]:
    parts = k.split("_HUMAN_")
    if len(parts) == 2:
        string_queries.append((parts[0] + "_HUMAN", parts[1]))
print(f"  {len(string_queries):,} STRING queries")

def string_network_900(mA, mB):
    net = set()
    for prot in (mA, mB):
        for partner, sc in prot_string.get(prot, {}).items():
            if sc >= 900 and partner not in (mA, mB):
                net.add(partner)
    return net

run_benchmark("STRING (≥900)", string_queries, string_network_900, "string_seqid")

print("\nAll done.")
